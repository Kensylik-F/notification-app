// Builds the template catalogue of notifications-kit from the service's own
// FreeMarker templates (contract/templates, copied from the service repository
// at the commit in contract/SOURCE.md). The service has no endpoint listing its
// templates, so this is where the composer learns which keys exist, which
// channels and languages each one renders for, and which variables it needs.
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';

/** Directory segment → channel enum of the contract. */
const CHANNEL_DIRS = {
  email: 'EMAIL',
  chat: 'CHAT',
  webhook: 'WEBHOOK',
  in_app: 'IN_APP',
};

/** application.yml: ludwig.notification.digest.template-key-suffix */
const DIGEST_SUFFIX = '-digest';

/** Names the renderer provides itself; a sender never supplies them. */
const PROVIDED = new Set(['recipient', 'locale']);

const dirs = path =>
  readdirSync(path)
    .filter(name => statSync(join(path, name)).isDirectory())
    .sort();

function stripComments(source) {
  return source.replace(/<#--[\s\S]*?-->/g, '');
}

/**
 * Variables of one template file.
 * - `${name}` without a default is required: the renderer is strict and a
 *   missing value fails the render;
 * - `${name!…}` and `<#if name??>` make it optional;
 * - `<#list name as item>` reads `name`; `item` is a loop variable.
 */
export function scanVariables(source) {
  const text = stripComments(source);
  const loopVars = new Set(
    [...text.matchAll(/<#list\s+([A-Za-z_]\w*)\s+as\s+([A-Za-z_]\w*)/g)].map(
      m => m[2]
    )
  );
  // `<#if name??>` guards every use of `name` inside the block; treating the
  // whole file as guarded is exact for these templates and errs on the side
  // of "optional", which the preview then checks against the real renderer.
  const guarded = new Set(
    [...text.matchAll(/<#if\s+([A-Za-z_]\w*)\s*\?\?/g)].map(m => m[1])
  );
  const required = new Set();
  const optional = new Set();
  const note = (name, isOptional) => {
    if (PROVIDED.has(name) || loopVars.has(name)) return;
    (isOptional || guarded.has(name) ? optional : required).add(name);
  };

  for (const m of text.matchAll(/\$\{\s*([A-Za-z_]\w*)([^}]*)\}/g)) {
    note(m[1], m[2].includes('!'));
  }
  for (const m of text.matchAll(/<#if\s+([A-Za-z_]\w*)\s*\?\?/g)) {
    note(m[1], true);
  }
  for (const m of text.matchAll(/<#list\s+([A-Za-z_]\w*)\s+as/g)) {
    note(m[1], false);
  }
  for (const m of text.matchAll(/<#if\s+([A-Za-z_]\w*)\s*[!=<>]/g)) {
    note(m[1], false);
  }

  const usesRecipient = /\brecipient\./.test(text);
  return { required, optional, usesRecipient };
}

export function buildCatalog(root) {
  const catalog = [];
  for (const key of dirs(root)) {
    const channels = {};
    const required = new Set();
    const optional = new Set();
    let usesRecipient = false;

    for (const channelDir of dirs(join(root, key))) {
      const channel = CHANNEL_DIRS[channelDir];
      if (!channel) continue;
      const locales = dirs(join(root, key, channelDir));
      channels[channel] = locales;
      for (const locale of locales) {
        const folder = join(root, key, channelDir, locale);
        for (const file of readdirSync(folder).sort()) {
          const scan = scanVariables(readFileSync(join(folder, file), 'utf8'));
          scan.required.forEach(v => required.add(v));
          scan.optional.forEach(v => optional.add(v));
          usesRecipient ||= scan.usesRecipient;
        }
      }
    }
    // A variable required by any part of any channel is required overall.
    required.forEach(v => optional.delete(v));

    catalog.push({
      key,
      channels,
      variables: [
        ...[...required].sort().map(name => ({ name, required: true })),
        ...[...optional].sort().map(name => ({ name, required: false })),
      ],
      // An announcement renders once for an audience: there is no recipient
      // to greet, and a template that references one fails at publish.
      announcement: !usesRecipient && !key.endsWith(DIGEST_SUFFIX),
      // Digest templates are filled by the service's own collapse job.
      digest: key.endsWith(DIGEST_SUFFIX),
    });
  }
  return catalog;
}

export function renderCatalog(catalog) {
  return (
    '// GENERATED by scripts/generate-templates.mjs from contract/templates.\n' +
    '// Do not edit by hand.\n' +
    "import type { TemplateDescriptor } from '../templates';\n\n" +
    `export const SERVICE_TEMPLATES: readonly TemplateDescriptor[] = ${JSON.stringify(
      catalog,
      null,
      2
    )};\n`
  );
}
